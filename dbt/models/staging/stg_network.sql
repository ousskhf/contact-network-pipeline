select
    row_number() over () as member_row,
    trim(concat_ws(' ', first_name, last_name)) as name,
    {{ split_phones('phone') }}[1] as phone_norm,
    coalesce({{ normalize_phone('phone2') }}, {{ split_phones('phone') }}[2]) as phone2_norm,
    boutique_code,
    numero_membre,
    grade,
    grade_id,
    not is_blocked as is_active,
    personal_sales_ttc,
    pending_personal_sales_ttc,
    team_sales_ttc,
    pending_team_sales_ttc,
    downline_sales_ttc,
    pending_downline_sales_ttc,
    nullif(trim(birth_date), '') as birth_date_raw,
    try_cast(left(nullif(trim(birth_date), ''), 10) as date) as birth_date,
    user_id,
    sponsor_id,
    depth,
    direct_count,
    personal_referrals,
    grade_at_start,
    eligible_grade,
    coalesce(is_promoted, false) as is_promoted
from {{ source('raw', 'network') }}
